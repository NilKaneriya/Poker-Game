// Runs every automated check of the server and saves one report:
//   lint, unit tests, MongoDB storage tests, end-to-end (JSON), end-to-end (MongoDB)
//
// Run from qa/:  npm run test:all                 -> qa/reports/automated/<date>.md
//                npm run test:all -- --skip-mongo  (no MongoDB download; JSON only)
//
// The checks themselves live in poker-server/ (they run in CI too); this script only runs
// them one after another, times them and writes down what happened.
const { spawn } = require('child_process');
const fs = require('fs');
const os = require('os');
const path = require('path');

const SERVER_DIR = path.join(__dirname, '..', '..', 'poker-server');
const REPORT_DIR = path.join(__dirname, '..', 'reports', 'automated');
const SKIP_MONGO = process.argv.includes('--skip-mongo');

const CHECKS = [
  { name: 'Lint (ESLint + Prettier)', script: 'lint' },
  { name: 'Unit tests', script: 'test' },
  { name: 'Storage tests on MongoDB', script: 'test:mongo', mongo: true },
  { name: 'End-to-end (JSON storage)', script: 'test:e2e' },
  { name: 'End-to-end (MongoDB)', script: 'test:e2e:mongo', mongo: true },
];

function run(script) {
  return new Promise((resolve) => {
    const started = Date.now();
    // One command string through the shell: works for npm on Windows (npm.cmd) and elsewhere.
    const child = spawn(`npm run ${script}`, { cwd: SERVER_DIR, shell: true });
    let out = '';
    child.stdout.on('data', (d) => (out += d));
    child.stderr.on('data', (d) => (out += d));
    child.on('close', (code) => resolve({ code, out, seconds: (Date.now() - started) / 1000 }));
  });
}

/** One-line summary from a check's output. */
function summarize(script, out) {
  const count = (label) => out.match(new RegExp(`^ℹ ${label} (\\d+)`, 'm'))?.[1];
  if (script === 'test' || script === 'test:mongo') {
    return `${count('tests') ?? '?'} tests: ${count('pass') ?? '?'} passed, ${count('fail') ?? '?'} failed`;
  }
  if (script === 'lint') return /All matched files use Prettier/.test(out) ? 'no lint or format issues' : 'issues found';
  const lines = out.trim().split('\n');
  return lines[lines.length - 1].trim(); // e2e prints OK or FAIL: reason
}

/** The failing tests (node:test) or the last lines, for the report. */
function failureDetails(out) {
  const failing = out.split('\n').filter((l) => l.startsWith('✖'));
  return (failing.length ? failing : out.trim().split('\n').slice(-15)).join('\n');
}

async function main() {
  const results = [];
  for (const check of CHECKS) {
    if (check.mongo && SKIP_MONGO) {
      results.push({ ...check, status: 'SKIPPED', summary: '--skip-mongo', seconds: 0 });
      continue;
    }
    process.stdout.write(`${check.name}... `);
    const { code, out, seconds } = await run(check.script);
    const status = code === 0 ? 'PASS' : 'FAIL';
    const summary = summarize(check.script, out);
    console.log(`${status} (${seconds.toFixed(0)} s) ${summary}`);
    results.push({ ...check, status, summary, seconds, details: code === 0 ? '' : failureDetails(out) });
  }

  const passed = results.every((r) => r.status !== 'FAIL');
  const date = new Date();
  const stamp = date.toLocaleString('sv').slice(0, 16).replace(' ', '_').replace(':', '-'); // local time
  const commit = await gitCommit();
  const text = `# Automated test run (${date.toLocaleString('sv').slice(0, 16)})

Generated by \`qa/scripts/run-all.js\`. **Overall: ${passed ? 'PASS' : 'FAIL'}**

| | |
|---|---|
| Commit | ${commit} |
| Machine | ${os.type()} ${os.release()}, Node ${process.version} |

| Check | npm script (poker-server/) | Result | Time | Summary |
|---|---|---|---|---|
${results.map((r) => `| ${r.name} | \`${r.script}\` | ${r.status} | ${r.seconds.toFixed(0)} s | ${r.summary} |`).join('\n')}
${results
  .filter((r) => r.details)
  .map((r) => `\n## ${r.name}: failure details\n\`\`\`\n${r.details}\n\`\`\``)
  .join('\n')}
`;
  fs.mkdirSync(REPORT_DIR, { recursive: true });
  const file = path.join(REPORT_DIR, `${stamp}.md`);
  fs.writeFileSync(file, text);
  console.log(`\n${passed ? 'All checks passed' : 'Some checks FAILED'}. Report saved: ${path.relative(path.join(__dirname, '..', '..'), file)}`);
  process.exitCode = passed ? 0 : 1;
}

function gitCommit() {
  return new Promise((resolve) => {
    const git = spawn('git', ['log', '-1', '--format=%h %s'], { cwd: SERVER_DIR });
    let out = '';
    git.stdout.on('data', (d) => (out += d));
    git.on('close', () => resolve(out.trim() || 'unknown'));
    git.on('error', () => resolve('unknown'));
  });
}

main();
